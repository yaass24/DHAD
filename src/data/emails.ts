export const getEmailTask = (id: string) => EMAILS.find((e) => e.id === id);

const DIACRITICS = /[ً-ْٰـ]/g;
const norm = (t: string) => t.replace(DIACRITICS, '').replace(/[أإآ]/g, 'ا').replace(/\s+/g, ' ').trim();

/** Runs the task's predefined checks over what the learner wrote. */
export function checkEmail(task: EmailTask, text: string) {
  const t = norm(text);
  return task.checks.map((c) => {
    const hasRequired = c.any.length === 0 || c.any.some((p) => p === '' || t.includes(norm(p)));
    const hasAvoided = (c.avoid ?? []).some((p) => t.includes(norm(p)));
    return { check: c, passed: hasRequired && !hasAvoided, foundAvoided: hasAvoided };
  });
}
